/** South of this latitude is treated as the Antarctic land cap. */
const ANTARCTIC_LAT = -70;

/** Standard ray-casting test in equirectangular space. */
function pointInRing(lng, lat, ring) {
  let inside = false;

  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];

    const straddles = yi > lat !== yj > lat;
    if (straddles && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }

  return inside;
}

export function isLand(lng, lat) {
  if (lat <= ANTARCTIC_LAT) return true;
  return LAND_RINGS.some((ring) => pointInRing(lng, lat, ring));
}
